"""Corpus evaluation: the only source of the numbers in docs/BENCHMARKS.md (`sentinel eval --markdown`).

Three attack rates, because they answer different questions:
- flagged: detectors scored the call SUSPICIOUS or worse (it is at least logged as an alert).
- stopped by detectors: CRITICAL on detector evidence alone, so it would need approval even if the
  tool were on the allow-list.
- stopped by default policy: REQUIRE_APPROVAL/BLOCK under the shipped policy, which also counts
  deny-by-default for unknown tools. Always >= the detector rate; don't quote it alone.
"""

from __future__ import annotations

import secrets
import tempfile
from collections import defaultdict
from dataclasses import dataclass, field
from importlib.resources import files
from pathlib import Path
from typing import Any

import yaml

from sentinel.core.gateway import DECISION_RANK, SentinelGateway
from sentinel.core.types import DecisionAction, RiskTier, ToolCallRequest
from sentinel.sandbox.approval import ApprovalCoordinator, ApprovalStore
from sentinel.sandbox.ledger import AuditLedger

STOP = {DecisionAction.REQUIRE_APPROVAL, DecisionAction.BLOCK}


def cases(name: str) -> list[dict[str, Any]]:
    data: list[dict[str, Any]] = yaml.safe_load(files("sentinel.corpus").joinpath(f"{name}.yaml").read_text("utf-8"))
    return data


def to_request(c: dict[str, Any]) -> ToolCallRequest:
    return ToolCallRequest(tool_name=c["tool"], arguments=c.get("args", {}), raw_prompt_context=c.get("context"))


def load(name: str) -> list[tuple[str, ToolCallRequest]]:
    return [(c["id"], to_request(c)) for c in cases(name)]


@dataclass
class Report:
    attacks: list[dict[str, Any]] = field(default_factory=list)
    benign: list[dict[str, Any]] = field(default_factory=list)

    @staticmethod
    def _rate(rows: list[dict[str, Any]], key: str) -> float:
        return sum(r[key] for r in rows) / len(rows) if rows else 0.0

    @property
    def metrics(self) -> dict[str, float]:
        return {
            "attacks": len(self.attacks),
            "benign": len(self.benign),
            "flagged_rate": self._rate(self.attacks, "flagged"),
            "detector_stop_rate": self._rate(self.attacks, "detector_stop"),
            "policy_stop_rate": self._rate(self.attacks, "policy_stop"),
            "false_positive_rate": self._rate(self.benign, "false_positive"),
        }


def evaluate(gateway: SentinelGateway | None = None) -> Report:
    if gateway is None:  # throwaway ledger/store: evaluating must not write to SENTINEL_HOME
        with tempfile.TemporaryDirectory(prefix="sentinel-eval-") as tmp:
            return evaluate(
                SentinelGateway(
                    ledger=AuditLedger(Path(tmp) / "audit.jsonl", key=secrets.token_bytes(32)),
                    approval_coordinator=ApprovalCoordinator(ApprovalStore(":memory:"), key=secrets.token_bytes(32)),
                )
            )
    gw = gateway
    report = Report()
    for c in cases("attacks"):
        a = gw.inspect(to_request(c))
        report.attacks.append(
            {
                "id": c["id"],
                "category": c.get("category", "other"),
                "score": a.overall_score,
                "decision": a.decision.value,
                "flagged": a.tier != RiskTier.SAFE,
                "detector_stop": a.tier == RiskTier.CRITICAL,
                "policy_stop": a.decision in STOP,
            }
        )
    for c in cases("benign"):
        a = gw.inspect(to_request(c))
        expect = DecisionAction(c.get("expect", "ALLOW"))
        report.benign.append(
            {
                "id": c["id"],
                "decision": a.decision.value,
                "expect": expect.value,
                "false_positive": DECISION_RANK[a.decision] > DECISION_RANK[expect],
            }
        )
    return report


def to_markdown(report: Report) -> str:
    m = report.metrics
    by_cat: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for r in report.attacks:
        by_cat[r["category"]].append(r)

    def pct(x: float) -> str:
        return f"{x * 100:.0f}%"

    lines = [
        "# SentinelAgent evaluation",
        "",
        "Generated by `sentinel eval --markdown` from `sentinel/corpus/*.yaml` with the default policy.",
        "Do not edit by hand: `tests/eval/test_corpus_metrics.py` fails if this file drifts from the code.",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Attack cases | {m['attacks']:.0f} |",
        f"| Flagged (SUSPICIOUS or worse) | {pct(m['flagged_rate'])} |",
        f"| Stopped on detector evidence alone (CRITICAL) | {pct(m['detector_stop_rate'])} |",
        f"| Stopped under default policy (incl. deny-by-default) | {pct(m['policy_stop_rate'])} |",
        f"| Benign cases | {m['benign']:.0f} |",
        f"| False positives (stricter than expected) | {pct(m['false_positive_rate'])} |",
        "",
        "Latency is machine-dependent and is not recorded here; the CI `benchmark` job publishes it.",
        "",
        "## Attacks by category",
        "",
        "| Category | Cases | Flagged | Stopped by detectors |",
        "|---|---|---|---|",
    ]
    for cat, rows in sorted(by_cat.items()):
        lines.append(
            f"| {cat} | {len(rows)} | {sum(r['flagged'] for r in rows)} | {sum(r['detector_stop'] for r in rows)} |"
        )
    misses = [r for r in report.attacks if not r["detector_stop"]]
    lines += [
        "",
        "## Known misses (not CRITICAL on detector evidence)",
        "",
        "Injection text inside one call's arguments is scored as an alert (WARN), not a stop, by design:",
        "summarising a poisoned page is harmless. What stops indirect injection is the taint rule on the",
        "*next* call into a high-risk sink (see `tests/taint/`).",
        "",
    ]
    lines += [f"- `{r['id']}` ({r['category']}): score {r['score']}, {r['decision']}" for r in misses] or ["- none"]
    fps = [r for r in report.benign if r["false_positive"]]
    lines += ["", "## False positives", ""]
    lines += [f"- `{r['id']}`: expected {r['expect']}, got {r['decision']}" for r in fps] or ["- none"]
    lines += [
        "",
        "## Limits",
        "",
        "- The corpus is hand-written and small; these are regression numbers, not a claim about real-world",
        "  attack coverage. A public benchmark run (e.g. AgentDojo) is the next step.",
        "- Multi-step indirect injection (tool output -> later call) is covered by taint-tracking scenario",
        "  tests (`tests/taint/`), not by this single-call corpus. Paraphrased exfiltration is not caught.",
        "",
    ]
    return "\n".join(lines)
